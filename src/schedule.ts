function gridKey(station: string, dayIndex: number): string {
  return station + dayIndex;
}

// Builds the upcoming week's day/person assignments from the Config data.
// Stations are a single global list (already validated unique by
// readStationsFromValues), applied in the same order to every included day.
// Days run in calendar order starting at startDate (not Sunday-Saturday
// order), so e.g. a Wednesday start date with Mon/Wed/Fri selected produces
// Wed, Fri, then next Mon.
function computeAssignments(config: WorkbookConfig): ScheduleAssignment {
  const tz = getSpreadsheetTz();
  const startDayIndex = getWeekdayIndex(config.startDate, tz);
  const errors: string[] = [];

  if (config.stations.length === 0) {
    errors.push("No stations are configured. Add at least one station to the Config sheet.");
    return { orderedDays: [], stationOrder: [], grid: {}, errors: errors };
  }

  const includedDays = config.days.filter(function (d) {
    return d.included;
  });

  const withOffsets = includedDays.map(function (d) {
    const offset = (d.dayIndex - startDayIndex + 7) % 7;
    return { day: d, offset: offset };
  });
  withOffsets.sort(function (a, b) {
    return a.offset - b.offset;
  });

  const orderedDays: ScheduledDay[] = [];
  const grid: { [key: string]: string } = {};

  withOffsets.forEach(function (entry) {
    const d = entry.day;
    if (d.roster.length === 0) {
      errors.push(d.dayName + " is included but has no roster listed.");
      return;
    }

    orderedDays.push({
      dayIndex: d.dayIndex,
      dayName: d.dayName,
      date: addCalendarDays(config.startDate, tz, entry.offset),
      roster: d.roster,
    });

    config.stations.forEach(function (station, i) {
      grid[gridKey(station, d.dayIndex)] = d.roster[i % d.roster.length];
    });
  });

  return { orderedDays: orderedDays, stationOrder: config.stations, grid: grid, errors: errors };
}

function formatDayHeader(day: ScheduledDay): string {
  return day.dayName + "\n" + formatSheetDate(day.date);
}

function readScheduleSnapshot(): ScheduleSnapshot | null {
  const raw = PropertiesService.getDocumentProperties().getProperty(SCHEDULE_SNAPSHOT_PROPERTY);
  if (!raw) {
    return null;
  }
  try {
    return JSON.parse(raw) as ScheduleSnapshot;
  } catch (e) {
    return null;
  }
}

function computeGridHash(sheet: GoogleAppsScript.Spreadsheet.Sheet, rows: number, cols: number): string {
  if (rows <= 0 || cols <= 0 || sheet.getMaxRows() < rows || sheet.getMaxColumns() < cols) {
    return "";
  }
  const json = JSON.stringify(sheet.getRange(1, 1, rows, cols).getValues());
  // Hash rather than store the raw JSON: Document Properties cap each value
  // at 9KB, which a large grid could exceed.
  const digest = Utilities.computeDigest(Utilities.DigestAlgorithm.SHA_256, json);
  return Utilities.base64Encode(digest);
}

function saveScheduleSnapshot(sheet: GoogleAppsScript.Spreadsheet.Sheet, rows: number, cols: number): void {
  const snapshot: ScheduleSnapshot = { rows: rows, cols: cols, hash: computeGridHash(sheet, rows, cols) };
  PropertiesService.getDocumentProperties().setProperty(
    SCHEDULE_SNAPSHOT_PROPERTY,
    JSON.stringify(snapshot)
  );
}

// True only when the Schedule sheet has previously been generated by this
// script AND the exact rectangle it last wrote no longer matches (i.e.
// someone hand-edited the printed grid since). This only ever looks at that
// rectangle, so unrelated content elsewhere on the sheet (e.g. announcements
// below the grid) never counts as a manual edit, and a sheet that's since
// been deleted or cleared below the saved extent is never flagged either.
function isScheduleDirty(sheet: GoogleAppsScript.Spreadsheet.Sheet): boolean {
  const saved = readScheduleSnapshot();
  if (!saved) {
    return false;
  }
  const currentHash = computeGridHash(sheet, saved.rows, saved.cols);
  if (currentHash === "") {
    return false;
  }
  return currentHash !== saved.hash;
}

function writeSchedule(
  sheet: GoogleAppsScript.Spreadsheet.Sheet,
  config: WorkbookConfig,
  assignment: ScheduleAssignment
): void {
  const numCols = assignment.orderedDays.length + 1;
  const gridRows = assignment.stationOrder.length;
  const titleRow = 1;
  const headerRow = 2;
  const totalRows = headerRow + gridRows;

  // Only clear the rectangle this script owns (the title, header, and
  // station rows), unioned with whatever extent was written last time, so a
  // shrinking grid doesn't leave stale cells behind. Anything below or
  // beside that — e.g. announcements the user maintains by hand — is left
  // untouched.
  const previous = readScheduleSnapshot();
  const clearRows = Math.max(totalRows, previous ? Math.min(previous.rows, sheet.getMaxRows()) : 0);
  const clearCols = Math.max(numCols, previous ? Math.min(previous.cols, sheet.getMaxColumns()) : 0);
  if (clearRows > 0 && clearCols > 0) {
    const clearRange = sheet.getRange(1, 1, clearRows, clearCols);
    // clear() does not unmerge cells on its own; without this, a title
    // merged across a different number of columns last time (a week with a
    // different day count) can leave a stale merge that the new merge()
    // below overlaps and rejects.
    clearRange.breakApart();
    clearRange.clear();
  }

  const titleRange = sheet.getRange(titleRow, 1, 1, numCols);
  titleRange.merge();
  sheet
    .getRange(titleRow, 1)
    .setValue(SCHEDULE_TITLE)
    .setFontWeight("bold")
    .setFontSize(24)
    .setFontColor("#1155CC")
    .setHorizontalAlignment("center")
    .setVerticalAlignment("middle");
  sheet.setRowHeight(titleRow, 50);

  const headerValues = [""].concat(assignment.orderedDays.map(formatDayHeader));
  const headerRange = sheet.getRange(headerRow, 1, 1, numCols);
  headerRange.setValues([headerValues]);
  headerRange
    .setFontWeight("bold")
    .setWrap(true)
    .setHorizontalAlignment("center")
    .setVerticalAlignment("middle")
    .setBackground("#D9D9D9")
    .setBorder(true, true, true, true, true, true);

  if (gridRows > 0) {
    const gridValues = assignment.stationOrder.map(function (station) {
      const row: string[] = [station];
      assignment.orderedDays.forEach(function (day) {
        row.push(assignment.grid[gridKey(station, day.dayIndex)] || "");
      });
      return row;
    });
    const bodyRange = sheet.getRange(headerRow + 1, 1, gridRows, numCols);
    bodyRange.setValues(gridValues);
    bodyRange
      .setFontWeight("bold")
      .setVerticalAlignment("middle")
      .setBorder(true, true, true, true, true, true);

    assignment.stationOrder.forEach(function (station, i) {
      sheet
        .getRange(headerRow + 1 + i, 1)
        .setBackground(STATION_ROW_COLORS[i % STATION_ROW_COLORS.length]);
    });
  }

  sheet.setFrozenRows(headerRow);
  sheet.setFrozenColumns(1);
  sheet.autoResizeColumns(1, numCols);

  saveScheduleSnapshot(sheet, totalRows, numCols);
}
